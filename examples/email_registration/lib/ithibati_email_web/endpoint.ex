defmodule IthibatiEmailWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :ithibati_email

  alias Ithibati.Identity.Sessions

  # Encrypted, not only signed: the session holds recovery codes until their page shows them.
  @session_options [
    store: :cookie,
    key: "_ithibati_email_key",
    signing_salt: "BJ4/B92x",
    encryption_salt: "2Lbc4XeE",
    same_site: "Lax"
  ]

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  # Browser requests need the test's sandboxed connection to see its data.
  if Application.compile_env(:ithibati_email, :sql_sandbox, false) do
    plug Phoenix.Ecto.SQL.Sandbox
  end

  plug Plug.Static,
    at: "/",
    from: :ithibati_email,
    gzip: not code_reloading?,
    only: IthibatiEmailWeb.static_paths()

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :ithibati_email
  end

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug :session
  plug IthibatiEmailWeb.Router

  # The cookie lasts as long as the session it carries, read when the request arrives so that
  # `session_validity` may be set in `config/runtime.exs`. Without it the browser drops the cookie
  # when it closes.
  defp session(conn, _opts) do
    options = Keyword.put(@session_options, :max_age, Sessions.max_age())
    Plug.Session.call(conn, Plug.Session.init(options))
  end
end
